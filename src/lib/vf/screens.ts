const toRe = (p: string) => new RegExp("^" + p.replace(/:[^/]+/g, "[^/]+").replace(/\/$/, "") + "/?$");
export function findScreen(path: string): Screen | undefined {
  const clean = path.replace(/\/$/, "") || "/";
  return SCREENS.find((s) => s.path === clean) ?? SCREENS.find((s) => toRe(s.path).test(clean));
}
/** Direct children in the registry (one segment deeper), for structural navigation. */
export function childScreens(path: string): Screen[] {
  const base = path.replace(/\/$/, "");
  const depth = base.split("/").length;
  return SCREENS.filter((s) => s.path.startsWith(base + "/") && s.path.split("/").length === depth + 1);
}
export function fillParams(p: string, from: string): string {
  const a = p.split("/"); const b = from.split("/");
  return a.map((seg, i) => (seg.startsWith(":") ? b[i] ?? "demo" : seg)).join("/");
}
